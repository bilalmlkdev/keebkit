// Regenerates the shadcn registry item and the in-app source snippets from the
// real component sources, so the published component never drifts from the site.
// Usage: node scripts/sync-registry.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const keyboardSrc = join(root, "src/components/ui/keyboard.tsx");
const themeDataSrc = join(root, "src/lib/keyboard-theme-data.ts");

const keyboardTsx = readFileSync(keyboardSrc, "utf8");
const themeDataTs = readFileSync(themeDataSrc, "utf8");

function toJsx(code, filename) {
  return ts.transpileModule(code, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      jsx: ts.JsxEmit.Preserve,
    },
    fileName: filename,
  }).outputText;
}

const keyboardJsx = toJsx(keyboardTsx, "keyboard.tsx");
const themeDataJs = toJsx(themeDataTs, "keyboard-theme-data.ts");

const registryItem = {
  $schema: "https://ui.shadcn.com/schema/registry-item.json",
  name: "keyboard",
  type: "registry:component",
  title: "Keyboard",
  description: "A Keychron-inspired keyboard component with haptics and mechanical sound effects.",
  dependencies: ["lucide-react"],
  files: [
    {
      path: "registry/keyboard.jsx",
      content: keyboardJsx,
      type: "registry:component",
      target: "components/ui/keyboard.jsx",
    },
    {
      path: "registry/keyboard-theme-data.js",
      content: themeDataJs,
      type: "registry:component",
      target: "lib/keyboard-theme-data.js",
    },
  ],
};

writeFileSync(join(root, "public/r/keyboard.json"), JSON.stringify(registryItem, null, 2) + "\n");

const generated = {
  tsx: keyboardTsx,
  jsx: keyboardJsx,
};

writeFileSync(
  join(root, "src/lib/generated-sources.ts"),
  `// Generated by scripts/sync-registry.mjs — do not edit by hand.\nexport const GENERATED_SOURCES = ${JSON.stringify(generated, null, 2)} as const;\n`,
);

console.log("Synced public/r/keyboard.json and src/lib/generated-sources.ts");
